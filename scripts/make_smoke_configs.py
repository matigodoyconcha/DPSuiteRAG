#!/usr/bin/env python
"""Derive ``experiments/configs/smoke/`` from ``experiments/configs/full/``.

The smoke set is the common protocol shrunk to one cell per method: one dataset,
one generator, five questions, one operating point on each budget knob. Its job is
to prove that all eight methods run end to end and to time a query, so that the
main grid is sized from measurements instead of estimates.

Generating it rather than hand-writing it keeps the two sets from drifting: every
structural parameter (thresholds, voter counts, chunking policy, metric lists)
comes from the full config verbatim, and only the axes below are overridden.

    python scripts/make_smoke_configs.py

The chosen budget point is each method's operating point, never the tightest one
on its grid -- at the low end several methods legitimately release nothing, and a
smoke run must not confuse an empty cell with a broken runner.
"""

from __future__ import annotations

import sys
from pathlib import Path

import yaml

PROJECT_ROOT = Path(__file__).resolve().parents[1]
FULL_DIR = PROJECT_ROOT / "experiments" / "configs" / "full"
SMOKE_DIR = PROJECT_ROOT / "experiments" / "configs" / "smoke"

# ChatDoctor: self-contained corpus, so the smoke run does not depend on the DPR
# passages being downloaded, and short documents keep the voting prompts inside
# OPT's 2048 positions.
DATASET = "chatdoctor"
# The corpus stays at the full protocol's size. Shrinking it would index faster, but
# the retrieval thresholds are calibrated against this many documents: at a tenth of
# the corpus MuRAG's tau=0.5 admits ~11 documents per query instead of ~108, short of
# the m*k=50 voters it needs. The method would run in a regime the main grid never
# reaches, and the per-query timings this run exists to produce would be measured on
# a fifth of the forward passes -- undersizing the grid rather than sizing it.
MAX_INDEX_DOCS = 20000
MAX_TEST_QUERIES = 5
MODEL = "facebook/opt-1.3b"  # smallest ungated generator of the shared sweep

# One value per budget knob, at each method's operating point.
EPSILON_POINTS: dict[str, dict[str, list[float]]] = {
    "dp_rag": {
        "epsilon_retrieval_values": [0.5],
        "epsilon_generation_values": [5.0],
    },
    "dpvoterag": {"epsilon_values": [10]},
    "dpsparsevoterag": {
        "epsilon_values": [20],
        "epsilon_token_values": [2],
    },
    "dpksa": {"epsilon_values": [3]},
    "private_rag": {"epsilon_q_values": [10], "epsilon_0_values": [1.0]},
    "private_rag_ada": {"epsilon_q_values": [10], "epsilon_0_values": [1.0]},
    # DP-SynRAG's knob is the noise multiplier of its four zCDP stages, nested
    # under synthetic_generation.
    "dp_synrag": {"synthetic_generation.c_values": [0.25]},
    "vanilla": {},
}

HEADER = """\
# GENERATED by scripts/make_smoke_configs.py -- do not edit by hand.
#
# The common protocol (experiments/configs/full/{name}.yaml) reduced to a single
# cell: {dataset}, {model}, {queries} questions, one point per budget knob. Used to
# verify that every method runs end to end and to time a query before the main
# grid is sized. Edit the full config and regenerate.
"""


def _set_nested(cfg: dict, dotted: str, value) -> None:
    *parents, leaf = dotted.split(".")
    node = cfg
    for part in parents:
        node = node.setdefault(part, {})
    node[leaf] = value


def build(name: str, full: dict) -> dict:
    cfg = dict(full)

    cell = {
        "name": DATASET,
        "max_index_docs": MAX_INDEX_DOCS,
        "max_test_queries": MAX_TEST_QUERIES,
    }
    cfg["datasets"] = [dict(cell)]
    # The singular block is the fallback the runners read when `datasets:` is
    # removed. It carries the same caps, so dropping the list cannot silently widen
    # the smoke cell to the full config's corpus.
    fallback = cfg.get("dataset")
    cfg["dataset"] = {**fallback, **cell} if isinstance(fallback, dict) else dict(cell)

    cfg["llms"] = [{"model_name": MODEL}]
    if isinstance(cfg.get("llm"), dict):
        cfg["llm"] = {**cfg["llm"], "model_name": MODEL}

    cfg["max_queries"] = MAX_TEST_QUERIES

    for knob, values in EPSILON_POINTS[name].items():
        _set_nested(cfg, knob, values)

    # Results land beside the full run's, under their own root.
    if "output_dir" in cfg:
        cfg["output_dir"] = f"results/smoke/{name}/"
    if "output_path" in cfg:
        cfg["output_path"] = f"results/smoke/{name}/{name}.json"

    return cfg


def main() -> int:
    SMOKE_DIR.mkdir(parents=True, exist_ok=True)
    for name in sorted(EPSILON_POINTS):
        src = FULL_DIR / f"{name}.yaml"
        with open(src, encoding="utf-8") as f:
            full = yaml.safe_load(f) or {}

        text = HEADER.format(
            name=name, dataset=DATASET, model=MODEL, queries=MAX_TEST_QUERIES
        ) + yaml.safe_dump(build(name, full), sort_keys=False, allow_unicode=True)

        dest = SMOKE_DIR / f"{name}.yaml"
        dest.write_text(text, encoding="utf-8")
        print(f"wrote {dest.relative_to(PROJECT_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
